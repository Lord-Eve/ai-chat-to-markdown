'use strict';
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
let source = fs.readFileSync(path.join(root, 'ai-chat-to-markdown.user.js'), 'utf8');
const configAnchor = '  /* ========================= 工具函数 ========================= */';
const readyAnchor = '  const ready = () => {';
for (const anchor of [configAnchor, readyAnchor]) {
  if (source.split(anchor).length !== 2) throw new Error(`Core build anchor changed: ${anchor}`);
}
source = source.replace(/^\/\/ ==UserScript==[\s\S]*?\/\/ ==\/UserScript==\s*/, '');
source = source.replace(configAnchor, `  Object.assign(CFG, extensionSettings);\n${configAnchor}`);
const bridge = fs.readFileSync(path.join(root, 'extension/bridge.js'), 'utf8');
source = source.replace(readyAnchor, `${bridge}\n${readyAnchor}`);
fs.writeFileSync(path.join(root, 'extension/content.js'), `// Generated by npm run build:extension. Do not edit.\n(async () => {\n${fs.readFileSync(path.join(root, 'extension/settings.js'), 'utf8')}\nconst stored = await chrome.storage.local.get('settings');\nconst extensionSettings = normalizeSettings(stored.settings);\n${source}\n})();\n`);
const manifestPath = path.join(root, 'extension/manifest.json');
const manifest = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
manifest.version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
fs.writeFileSync(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
console.log('Built extension/content.js');
